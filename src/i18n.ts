export const DICTIONARIES: Record<Lang, Record<Key, string>> = { fr, en };

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: Key, vars?: Vars): string {
  const template = DICTIONARIES[lang][key] ?? fr[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_m, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
}

/** Picks `key.one` or `key.other` by count (French treats 0 as singular). */
export function translatePlural(lang: Lang, base: string, n: number, vars?: Vars): string {
  const one = lang === "fr" ? n < 2 : n === 1;
  return translate(lang, `${base}.${one ? "one" : "other"}` as Key, { n, ...vars });
}

export interface Translator {
  lang: Lang;
  t: (key: Key, vars?: Vars) => string;
  /** Plural form: tp("library.count", 3) → "3 livres". */
  tp: (base: PluralBase, n: number, vars?: Vars) => string;
}

type PluralBase = {
  [K in Key]: K extends `${infer B}.one` ? B : never;
}[Key];

export function makeTranslator(lang: Lang): Translator {
  return {
    lang,
    t: (key, vars) => translate(lang, key, vars),
    tp: (base, n, vars) => translatePlural(lang, base, n, vars),
  };
}

const translators: Partial<Record<Lang, Translator>> = {};

/** One translator object per language, so memoised children keep a stable prop identity. */
export function getTranslator(lang: Lang): Translator {
  return (translators[lang] ??= makeTranslator(lang));
}

export function useT(): Translator {
  const { settings } = useSettings();
  return getTranslator(settings.lang);
}
